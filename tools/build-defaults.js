#!/usr/bin/env node
/* Bundles content/*.json into data/defaults.js.
   That file is only used when the site is opened straight off disk with
   file://, where fetch is blocked. Re-run after editing content:
     node tools/build-defaults.js                                          */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DOCS = { theme: "THEME", site: "SITE", text: "TEXT",
               menu: "MENU", deals: "DEALS", specials: "SPECIALS" };

var out = ["/* GENERATED by tools/build-defaults.js — do not edit by hand.",
           "   Offline fallback for file:// previews; the live site reads content/*.json. */",
           ""];

Object.keys(DOCS).forEach(function (name) {
  const file = path.join(ROOT, "content", name + ".json");
  const json = JSON.parse(fs.readFileSync(file, "utf8"));
  /* menu.json wraps its list; the page wants the array. */
  const value = name === "menu" ? json.categories : json;
  out.push("window." + DOCS[name] + " = " + JSON.stringify(value, null, 2) + ";");
  out.push("");
});

/* The hero video path lives under theme but the page reads it off SITE. */
out.push("if (window.THEME && window.THEME.heroVideo) window.SITE.heroVideo = window.THEME.heroVideo;");
out.push("");

const dest = path.join(ROOT, "data", "defaults.js");
fs.writeFileSync(dest, out.join("\n"));
console.log("Wrote " + path.relative(ROOT, dest) + " (" + (fs.statSync(dest).size / 1024).toFixed(1) + " KB)");
